// AccountDossier is the packed account dossier the server hands back for
// CMD_REQ_PLAYER_INFO: every achievement the client declares, at its maximum.
//
// It is NOT hand-authored. The client's own `dossiers2` builders produce it,
// which is the only way to get a blob the same build accepts — the layout is
// a versioned header of per-block sizes followed by the blocks, and every
// record's width and offset comes from `dossiers2.custom.records.RECORDS`.
// Regenerate with the pyconsole mod (py2.7, on the game's main thread):
//
//	import dossiers2, binascii
//	from dossiers2.custom import records
//	from dossiers2.ui import achievements as A
//	ACH = set(["achievements","achievements7x7","historicalAchievements",
//	           "fortAchievements","clanAchievements","achievementsRated7x7",
//	           "falloutAchievements","epicBattleAchievements",
//	           "steamAchievements","singleAchievements","uniqueAchievements",
//	           "vehicleAchievements","customizationAchievements",
//	           "playerBadges","commendations","prestigeSystem",
//	           "markOfMasteryCut","total"])
//	d = dossiers2.getAccountDossierDescr("")
//	for r in records.RECORDS:
//	    if len(r) != 5:
//	        continue
//	    block, rec, typ, fmt, mx = r
//	    if block not in ACH:
//	        continue
//	    try:
//	        d[block][rec] = mx
//	    except Exception:
//	        pass
//	for (block, name) in A.ACHIEVEMENTS.keys():
//	    if block == "singleAchievements":
//	        d["singleAchievements"].add(name)
//	    elif block == "uniqueAchievements":
//	        d["uniqueAchievements"].add(name)
//	from gui.doc_loaders.badges_loader import getAvailableBadges
//	ts = int(time.time())
//	for bid in getAvailableBadges():
//	    d["playerBadges"][bid] = ts
//	print(binascii.hexlify(d.makeCompDescr()))
//
// `records.RECORDS` is the whole layout: `(block, record, type, format,
// maxValue)` per record, so "set every record to its maxValue" is exactly
// "unlock everything". The two set blocks (`singleAchievements`,
// `uniqueAchievements`) are bitmasks keyed by achievement NAME, and
// `dossiers2.ui.achievements.ACHIEVEMENTS` is the name table.
//
// The achievement blocks, `total` and `playerBadges` are filled; the rest
// stay at size 0. `playerBadges` is what `Badge.isAchieved` tests
// (`receivedBadges = dossier[BADGES_BLOCK]`, then `badgeID in receivedBadges`
// with the value as `achievedAt`), so it is the badge unlock list — every
// badge `gui.doc_loaders.badges_loader.getAvailableBadges()` returns, stamped
// with the generation time.
//
// That makes the blob 2677 B, past the channel MTU, so the answer rides the
// fragment chain (`BaseAppServer.mintPostLarge`). Filling every block (the
// `max*` and per-mode stat blocks too) would make it ~7 KB.
